[CmdletBinding()]
param(
    [string]$OutputDirectory
)

$ErrorActionPreference = "Stop"
$serverRoot = (Resolve-Path (Join-Path $PSScriptRoot "..\..")).Path
$packagePath = Join-Path $serverRoot "package.json"
$package = Get-Content -Raw $packagePath | ConvertFrom-Json
$version = [string]$package.version

if ([string]::IsNullOrWhiteSpace($OutputDirectory)) {
    $OutputDirectory = Join-Path $serverRoot "build\engineering-artifacts"
}
$OutputDirectory = [System.IO.Path]::GetFullPath($OutputDirectory)
New-Item -ItemType Directory -Force -Path $OutputDirectory | Out-Null

$workRoot = Join-Path $env:TEMP "loom-node-bundle-$([Guid]::NewGuid().ToString('N'))"
$bundleName = "loom-node-$version"
$bundleRoot = Join-Path $workRoot $bundleName
$zipPath = Join-Path $OutputDirectory "$bundleName-windows-docker.zip"

try {
    New-Item -ItemType Directory -Force -Path $bundleRoot | Out-Null
    New-Item -ItemType Directory -Force -Path (Join-Path $bundleRoot "scripts\windows") | Out-Null
    New-Item -ItemType Directory -Force -Path (Join-Path $bundleRoot "deploy") | Out-Null

    New-Item -ItemType Directory -Force -Path (Join-Path $bundleRoot "scripts\linux") | Out-Null
    Copy-Item (Join-Path $serverRoot "scripts\linux\go-build-resources.sh") (Join-Path $bundleRoot "scripts\linux\go-build-resources.sh")

    Copy-Item (Join-Path $serverRoot "package.json") $bundleRoot
    Copy-Item (Join-Path $serverRoot "package-lock.json") $bundleRoot
    Copy-Item (Join-Path $serverRoot "src") (Join-Path $bundleRoot "src") -Recurse

    # Copy only checked-in deployment inputs. Never copy deploy\.env because it
    # contains the live admin/database/object-store secrets generated by setup.
    $deployFiles = @(
        "Dockerfile",
        "Dockerfile.storage",
        "STORAGE.md",
        "docker-compose.production.yml",
        "Caddyfile.example",
        ".env.example",
        "README.md"
    )
    foreach ($name in $deployFiles) {
        Copy-Item (Join-Path $serverRoot "deploy\$name") (Join-Path $bundleRoot "deploy\$name")
    }

    $scriptNames = @(
        "setup-production.ps1",
        "setup-production.cmd",
        "status-production.ps1",
        "status-production.cmd"
    )
    foreach ($name in $scriptNames) {
        Copy-Item (Join-Path $PSScriptRoot $name) (Join-Path $bundleRoot "scripts\windows\$name")
    }

    $bundleReadme = @"
Loom Node $version - Production Docker Bundle
================================================

Prerequisite: Docker Desktop/Engine with Docker Compose v2.
No host Node.js, PostgreSQL, MinIO, or Caddy installation is required.

Example setup from this extracted directory:

  scripts\windows\setup-production.cmd -Domain chat.example.com

Then inspect readiness with:

  scripts\windows\status-production.cmd

Read deploy\README.md before exposing the Node to the public Internet.
"@
    $utf8WithoutBom = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText((Join-Path $bundleRoot "README.txt"), $bundleReadme, $utf8WithoutBom)

    if (Test-Path $zipPath) {
        Remove-Item -Force $zipPath
    }
    Compress-Archive -Path $bundleRoot -DestinationPath $zipPath -CompressionLevel Optimal
    Write-Host "Loom Node bundle: $zipPath"
} finally {
    Remove-Item -Recurse -Force $workRoot -ErrorAction SilentlyContinue
}
